//! The catalog texts as Fluent messages for the app: one
//! `catalog.ftl` per locale in `crates/services/i18n`. English comes from the
//! TOML. Other locales keep what their file already translates and fall
//! back to English with a mark for the translators.

#[cfg(test)]
mod tests;

use std::collections::HashMap;
use std::fs;
use std::path::Path;

use toolbox_catalog::{ColourSchemeCatalog, ConfigFileCatalog, ToggleCatalog};

use crate::catalogs::{SOURCE_DIR, TOGGLE_FILES};
use crate::translations::{plain_value, unmarked_values};
use crate::{ENGLISH, Failure, LOCALES_DIR, flags, root};

const FILE: &str = "catalog.ftl";
pub const UNTRANSLATED: &str = "# untranslated";
/// The id part of the Config Files catalog, its file name without `.toml`.
const CONFIG_CODE: &str = "config-files";
const SCHEMES_CODE: &str = "colour-schemes";

#[derive(Debug, PartialEq, Eq)]
pub struct Message {
    pub id: String,
    pub english: String,
}

impl Message {
    fn new(id: String, english: &str) -> Self {
        Self {
            id,
            english: english.to_owned(),
        }
    }
}

/// Every text of `catalog` in file order. `code` is the catalog's file
/// name without `.toml`, so ids stay unique across catalogs.
pub fn messages(code: &str, catalog: &ToggleCatalog) -> Vec<Message> {
    catalog
        .sections()
        .iter()
        .flat_map(|section| {
            let heading = Message::new(format!("catalog-{code}-{}", section.id()), section.title());
            let entries = section.entries().iter().flat_map(|entry| {
                let id = format!("catalog-{code}-{}", entry.id());
                [
                    Message::new(format!("{id}-description"), entry.description()),
                    Message::new(id, entry.title()),
                ]
                .into_iter()
                .rev()
            });

            std::iter::once(heading).chain(entries)
        })
        .collect()
}

/// Every text of the Config Files catalog in file order: section titles,
/// entry names and their descriptions where they have one.
pub fn config_messages(code: &str, catalog: &ConfigFileCatalog) -> Vec<Message> {
    catalog
        .sections()
        .iter()
        .flat_map(|section| {
            let heading = Message::new(format!("catalog-{code}-{}", section.id()), section.title());
            let entries = section.entries().iter().flat_map(|entry| {
                let id = format!("catalog-{code}-{}", entry.id());
                let description = entry
                    .description()
                    .map(|text| Message::new(format!("{id}-description"), text));

                std::iter::once(Message::new(id, entry.name())).chain(description)
            });

            std::iter::once(heading).chain(entries)
        })
        .collect()
}

pub fn scheme_messages(code: &str, catalog: &ColourSchemeCatalog) -> Vec<Message> {
    catalog
        .schemes()
        .iter()
        .map(|scheme| Message::new(format!("catalog-{code}-{}", scheme.id()), scheme.name()))
        .collect()
}

/// The file for `locale`. `translate` gives a finished value (already
/// escaped) or `None`, which keeps the English with a mark.
pub fn render(
    locale: &str,
    messages: &[Message],
    translate: impl Fn(&Message) -> Option<String>,
) -> String {
    let mut text = format!(
        "# Generated by `cargo xtask catalog-ftl` from {SOURCE_DIR}.\n\
         # {}\n",
        if locale == ENGLISH {
            "Do not edit: the English comes from the catalogs."
        } else {
            "Translate in place: a run keeps every value without the mark."
        }
    );

    for message in messages {
        text.push('\n');
        let english = || format!("{} = {}", message.id, plain_value(&message.english));
        let line = if locale == ENGLISH {
            english()
        } else {
            translate(message).map_or_else(
                || format!("{UNTRANSLATED}\n{}", english()),
                |value| format!("{} = {value}", message.id),
            )
        };

        text.push_str(&line);
    }

    text.push('\n');
    text
}

pub fn kept(file: &str) -> HashMap<String, String> {
    unmarked_values(file).into_iter().collect()
}

/// Writes every locale's `catalog.ftl`, or with `--check` fails when one
/// differs from what it would write.
pub fn catalog_ftl(args: &[String]) -> Result<String, Failure> {
    let check = !flags(args, &["--check"]).ok_or(Failure::Usage)?.is_empty();

    let all = all_messages(&root().join(SOURCE_DIR))
        .map_err(|problem| Failure::Problems(vec![problem]))?;

    let locales = root().join(LOCALES_DIR);
    let mut stale = Vec::new();

    for locale in locale_names(&locales).map_err(|problem| Failure::Problems(vec![problem]))? {
        let target = locales.join(&locale).join(FILE);
        let current = fs::read_to_string(&target).unwrap_or_default();
        let text = locale_file(&locale, &all, &current);

        if current == text {
            continue;
        }

        if check {
            stale.push(format!(
                "{} is out of date: run `cargo xtask catalog-ftl`",
                target.display()
            ));
        } else {
            fs::write(&target, text).map_err(|error| {
                Failure::Problems(vec![format!("cannot write {}: {error}", target.display())])
            })?;
        }
    }

    if !stale.is_empty() {
        return Err(Failure::Problems(stale));
    }

    Ok(format!(
        "{} catalog texts in {LOCALES_DIR}/*/{FILE}",
        all.len()
    ))
}

fn all_messages(dir: &Path) -> Result<Vec<Message>, String> {
    let mut all = Vec::new();

    for file in TOGGLE_FILES {
        let catalog = ToggleCatalog::load(dir, file).map_err(|error| error.to_string())?;
        let code = file.strip_suffix(".toml").unwrap_or(file);
        all.extend(messages(code, &catalog));
    }

    let configs = ConfigFileCatalog::load(dir).map_err(|error| error.to_string())?;
    all.extend(config_messages(CONFIG_CODE, &configs));

    let schemes = ColourSchemeCatalog::load(dir).map_err(|error| error.to_string())?;
    all.extend(scheme_messages(SCHEMES_CODE, &schemes));

    Ok(all)
}

fn locale_names(dir: &Path) -> Result<Vec<String>, String> {
    let mut names: Vec<String> = fs::read_dir(dir)
        .map_err(|error| format!("cannot list {}: {error}", dir.display()))?
        .filter_map(|entry| entry.ok()?.file_name().into_string().ok())
        .collect();

    names.sort();
    Ok(names)
}

fn locale_file(locale: &str, all: &[Message], current: &str) -> String {
    let existing = kept(current);

    render(locale, all, |message| existing.get(&message.id).cloned())
}
